#!/usr/bin/env python3
"""Embed a CKML model in the core as a generated source file.

  python3 tools/embed_ml_model.py sites   MODEL.ckml CARD.json   -> src/ml_builtin_sites.inc
  python3 tools/embed_ml_model.py locator MODEL.ckml CARD.json   -> src/ml_builtin_locator.inc
  python3 tools/embed_ml_model.py refiner MODEL.ckml CARD.json   -> src/ml_builtin_refiner.inc
  python3 tools/embed_ml_model.py --check                        (CI: each file's bytes match its recorded SHA-256)

Models are trained and evaluated in clearkeysolutions/key-test (ml/run_sites.sh,
ml/run_locator.sh); the card records the data seeds, the ckey commit and the
evaluation. A built-in model only proposes or reads; Reed-Solomon and CRC-32C decide.
"""
import hashlib, json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NAMES = {"sites": ("ml_builtin_sites.inc", "kMlBuiltinSites"), "locator": ("ml_builtin_locator.inc", "kMlBuiltinLocator"),
         "refiner": ("ml_builtin_refiner.inc", "kMlBuiltinRefiner")}


def write(kind, model, card):
    data = Path(model).read_bytes()
    if data[:4] != b"CKML":
        raise SystemExit("not a CKML model")
    meta = json.loads(Path(card).read_text())
    sha = hashlib.sha256(data).hexdigest()
    if meta.get("sha256") and meta["sha256"] != sha:
        raise SystemExit("model does not match its card")
    fname, sym = NAMES[kind]
    lines = [f"// Generated by tools/embed_ml_model.py; do not edit.",
             f"// Built-in ML {kind} model. sha256 {sha}",
             f"// Source: clearkeysolutions/key-test {meta.get('model')}, tag {meta.get('tag')}, width {meta.get('width')},",
             f"// {meta.get('training_cases')} fresh-seed training cases ({meta.get('plan_master_seed')}), trained against ckey {str(meta.get('ckey_commit'))[:12]}.",
             f"// Evaluation: key-test ml/locator-models/{Path(model).stem}.eval.md",
             f"constexpr size_t {sym}Size = {len(data)};",
             f"alignas(4) const uint8_t {sym}[{len(data)}] = {{"]
    for i in range(0, len(data), 24):
        lines.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    lines.append("};")
    (ROOT / "src" / fname).write_text("\n".join(lines) + "\n")
    print(f"wrote src/{fname}: {len(data)} bytes, sha256 {sha}")


def check():
    bad = 0
    for kind, (fname, sym) in NAMES.items():
        p = ROOT / "src" / fname
        if not p.exists():
            continue
        text = p.read_text()
        want = re.search(r"sha256 ([0-9a-f]{64})", text).group(1)
        body = text[text.index("{") + 1:text.rindex("}")]
        data = bytes(int(x) for x in re.findall(r"\d+", body))
        size = int(re.search(rf"{sym}Size = (\d+)", text).group(1))
        ok = hashlib.sha256(data).hexdigest() == want and len(data) == size
        print(f"{fname}: {'ok' if ok else 'MISMATCH'}")
        bad += not ok
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    if sys.argv[1:] == ["--check"]:
        check()
    elif len(sys.argv) == 4 and sys.argv[1] in NAMES:
        write(*sys.argv[1:])
    else:
        raise SystemExit(__doc__)
