#!/usr/bin/env python3
"""Generate the tiny on-device CKey border-component ranker.

This is deliberately a candidate ranker, not a decoder.  It is trained from
deterministic synthetic component measurements, while the native geometry
fit and RS/CRC checks remain the authority for accepting a CKey.  Replace or
augment the synthetic distributions with labelled camera captures as they are
collected; the output stays a dependency-free Swift source file.
"""
import argparse
from pathlib import Path
import numpy as np
from sklearn.linear_model import LogisticRegression

parser = argparse.ArgumentParser(description="Train the on-device CKey candidate ranker.")
parser.add_argument("--features", type=Path, help="CSV emitted by train_synthetic_locator.py")
args = parser.parse_args()

if args.features:
    rows = np.loadtxt(args.features, delimiter=",", skiprows=1)
    if rows.ndim != 2 or rows.shape[1] != 4:
        raise SystemExit("feature CSV must contain label,aspect_error,fill_ratio,relative_side")
    labels, features = rows[:, 0], rows[:, 1:]
else:
    # Kept only as a dependency-light smoke path. Production updates should
    # use the encoded/rasterized corpus generated by train_synthetic_locator.
    rng = np.random.default_rng(0xC1E7)
    count = 12_000
    positive = np.column_stack((
        np.abs(rng.normal(.035, .035, count)),
        np.clip(rng.normal(.09, .045, count), .005, .28),
        np.clip(rng.normal(.32, .16, count), .06, .72),
    ))
    negative = np.column_stack((
        np.abs(rng.normal(.42, .32, count)),
        np.clip(rng.beta(2, 3, count) * .8, .01, .95),
        rng.uniform(.01, .98, count),
    ))
    features = np.vstack((positive, negative))
    labels = np.r_[np.ones(count), np.zeros(count)]
# Keep the generated Swift feature contract identical to CameraScanner: the
# source CSV carries a relative side, while the on-device ranker converts it
# to distance from the useful 0.32 frame fraction.
features = features.copy()
features[:, 2] = np.abs(features[:, 2] - .32)
model = LogisticRegression(C=3, max_iter=2000, random_state=0).fit(features, labels)
weights = model.coef_[0]
bias = model.intercept_[0]
target = Path(__file__).parents[1] / "ios/CKeyReader/LocatorRanker.swift"
target.write_text(f'''// Generated by tools/train_locator_ranker.py. Do not hand-tune.\n\nimport Foundation\n\nenum LocatorRanker {{\n    private static let weights = [{weights[0]:.8f}, {weights[1]:.8f}, {weights[2]:.8f}]\n    private static let bias = {bias:.8f}\n\n    static func score(aspectError: Double, fillRatio: Double, relativeSide: Double) -> Double {{\n        let sideError = abs(relativeSide - 0.32)\n        let z = bias + weights[0] * aspectError + weights[1] * fillRatio + weights[2] * sideError\n        return 1.0 / (1.0 + exp(-z))\n    }}\n}}\n''')
print(f"wrote {target}; training accuracy={model.score(features, labels):.3f}; examples={len(labels)}")
