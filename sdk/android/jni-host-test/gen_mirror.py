#!/usr/bin/env python3
"""Generate a Java mirror of CKeyNative.kt's external declarations.

The mirror has exactly the JVM signatures the Kotlin compiler produces for
`@JvmStatic external fun` in an `object` (static native methods), so
`javac -h` on it yields the JNI prototypes the bridge must implement.
Usage: gen_mirror.py <CKeyNative.kt> <out_dir>
"""
import os
import re
import sys

TYPES = {
    "Int": "int", "Long": "long", "Boolean": "boolean", "Double": "double", "Float": "float",
    "Short": "short", "Byte": "byte", "Char": "char", "Unit": "void",
    "String": "String", "ByteArray": "byte[]", "IntArray": "int[]", "LongArray": "long[]",
    "DoubleArray": "double[]", "FloatArray": "float[]", "ByteBuffer": "java.nio.ByteBuffer",
}


def jtype(kotlin: str) -> str:
    t = kotlin.strip().rstrip("?")
    if t not in TYPES:
        sys.exit(f"gen_mirror: unmapped Kotlin type {kotlin!r}")
    return TYPES[t]


def main() -> None:
    src = open(sys.argv[1], encoding="utf-8").read()
    pattern = re.compile(r"@JvmStatic\s+external\s+fun\s+(\w+)\s*\((.*?)\)\s*(?::\s*([\w?]+))?\s*(?=\n)", re.S)
    methods = []
    for name, params, ret in pattern.findall(src):
        args = []
        for p in [p.strip() for p in params.split(",") if p.strip()]:
            pname, ptype = [x.strip() for x in p.split(":", 1)]
            args.append(f"{jtype(ptype)} {pname}")
        methods.append(f"    public static native {jtype(ret or 'Unit')} {name}({', '.join(args)});")
    if not methods:
        sys.exit("gen_mirror: no external functions found")
    out = os.path.join(sys.argv[2], "org", "openckey", "ckey")
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "CKeyNative.java"), "w", encoding="utf-8") as f:
        f.write("// GENERATED by gen_mirror.py from CKeyNative.kt. Do not edit.\n")
        f.write("package org.openckey.ckey;\n\npublic final class CKeyNative {\n")
        f.write("    static { System.load(System.getProperty(\"org.openckey.ckey.library\")); }\n")
        f.write("\n".join(methods) + "\n}\n")
    with open(os.path.join(out, "CKeyException.java"), "w", encoding="utf-8") as f:
        f.write("// GENERATED mirror of CKeyException.kt (the JNI-visible constructor).\n")
        f.write("package org.openckey.ckey;\n\npublic class CKeyException extends RuntimeException {\n"
                "    public final int status;\n"
                "    public CKeyException(int status, String message) { super(message); this.status = status; }\n"
                "    public int getStatus() { return status; }\n}\n")
    print(f"gen_mirror: {len(methods)} native methods")


if __name__ == "__main__":
    main()
